"""Qualitative prompt -> control examples (production adapters) for tables/T_prompt_examples.tex.

Prompts chosen to span dims, tags, negation and environment, including failures; outputs are not edited.
python -m steer.paper.adapter_examples -> paper/results/adapter_examples.json + paper/tables/T_prompt_examples.tex
"""
import json

import torch

from ..prompt import PromptMapper
from .common import RES

PROMPTS = [
    "Speak slowly and calmly, with a deep voice.",
    "Whisper it, as if you're telling a secret.",
    "Shout it angrily!",
    "Sound bored and a little tired.",
    "Ask it like a question, with a rising ending.",
    "Read it fast and cheerfully, like a sports commentator.",
    "With a shaky, trembling voice, terrified.",
    "Don't speak too fast.",
    "In a busy cafe, and laugh at the end.",
]
SHORT = {"rate": "rate", "loud": "loud", "f0_med": "F0med", "f0_iqr": "F0iqr", "f0_end": "F0end", "pause": "pause",
         "tilt": "tilt", "voiced": "voiced", "flat": "flat", "centroid": "centr", "cpps": "cpps", "h1h2": "h1h2"}


def tex_escape(s):
    return s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("'", "'")


def main():
    torch.set_num_threads(8)
    pm, pe = PromptMapper(device="cpu"), PromptMapper(device="cpu", env=True)
    rows = []
    for p in PROMPTS:
        r, e = pm(p), pe(p)
        env = dict(e.get("env", {}))
        env.update({f"ev_{k}": v for k, v in e.get("events", {}).items() if v})
        rows.append(dict(prompt=p, ctrl=r["ctrl"], top_tags=r["top_tags"], env=env))
        print(rows[-1])
    json.dump(dict(adapter="data/meta/prompt_adapter.pt (+ prompt_adapter_env.pt for env/events)", rows=rows),
              open(RES / "adapter_examples.json", "w"), indent=1)
    L = ["% generated by steer/paper/adapter_examples.py (PromptingNemo) from results/adapter_examples.json -- do not edit",
         "\\begin{table*}[t]", "\\centering\\small", "\\setlength{\\tabcolsep}{4pt}",
         "\\begin{tabular}{@{}p{5.2cm}p{4.6cm}ll@{}}", "\\toprule",
         "Prompt & Specified controls ($z$) & Tag ($p$) & Env./event \\\\", "\\midrule"]
    for r in rows:
        c = ", ".join(f"\\ctrl{{{tex_escape(SHORT[k])}}}\\,{v:+.1f}" for k, v in r["ctrl"].items()) or "--"
        t, pr = r["top_tags"][0]
        env = ", ".join(f"{k.replace('ev_', '')}: {v}" for k, v in r["env"].items()) or "--"
        L.append(f"\\emph{{{tex_escape(r['prompt'])}}} & {c} & {tex_escape(t)} ({pr:.2f}) & {tex_escape(env)} \\\\")
    L += ["\\bottomrule", "\\end{tabular}",
          "\\caption{Production adapter outputs, unedited. Controls are listed only where the ``specified'' probability "
          "exceeds 0.5; values are speaker-relative $z$. Tag = top-1 with its probability. The environment/event column "
          "comes from the environment variant of the adapter. The last-but-one row is a negation failure.}",
          "\\label{tab:prompt_examples}", "\\end{table*}"]
    open(RES.parent / "tables" / "T_prompt_examples.tex", "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
